#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///

"""Generate babel::spirv's opcode table from the SPIR-V headers the repo carries.

Run it as an explicit step after the headers move, never from the build:

    uv run libs/data/babel-data/tools/gen-spirv-opcodes.py --write
    uv run libs/data/babel-data/tools/gen-spirv-opcodes.py --check    # exit 2 when the committed table differs

`dev.py check` runs --check (and --write under --fix), so a hand edit to the table or a header bump nobody
regenerated after fails the gate.

The source is extern/spirv-reflect's unified1/spirv.h, whose utility code states, per opcode, its name and whether it
has a result id and a result type.
babel-data itself stays externals-free: the header is read here, and only the table it yields is compiled.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
HEADER = REPO / "extern" / "spirv-reflect" / "include" / "spirv" / "unified1" / "spirv.h"
TABLE = REPO / "libs" / "data" / "babel-data" / "src" / "babel-data" / "shader" / "spirv_opcode_table.cc"
COMMAND = "uv run libs/data/babel-data/tools/gen-spirv-opcodes.py --write"


def read_header() -> tuple[list[tuple[int, str, bool, bool]], str]:
    text = HEADER.read_text(encoding="utf-8")
    version = re.search(r"#define SPV_VERSION (0x[0-9a-fA-F]+)", text).group(1)
    revision = re.search(r"#define SPV_REVISION (\d+)", text).group(1)
    enum = text[text.index("typedef enum SpvOp_"):]
    enum = enum[: enum.index("} SpvOp;")]
    numbers = {}
    for m in re.finditer(r"SpvOp(\w+) = (\d+),", enum):
        if m.group(1) != "Max":
            numbers.setdefault(m.group(1), int(m.group(2)))
    has = text[text.index("inline void SpvHasResultAndType"):]
    has = has[: has.index("\n}\n")]
    flags = {}
    for m in re.finditer(r"case SpvOp(\w+): \*hasResult = (true|false); \*hasResultType = (true|false); break;", has.replace("\n", " ").replace("  ", " ")):
        flags[m.group(1)] = (m.group(2) == "true", m.group(3) == "true")
    if not flags:
        # one statement a line, as the header writes it
        for m in re.finditer(r"case SpvOp(\w+):\s*\*hasResult = (true|false);\s*\*hasResultType = (true|false);", has):
            flags[m.group(1)] = (m.group(2) == "true", m.group(3) == "true")
    names = {}
    to_string = text[text.index("inline const char* SpvOpToString"):]
    to_string = to_string[: to_string.index("\n}\n")]
    for m in re.finditer(r'case SpvOp(\w+):\s*return "(\w+)";', to_string):
        names[m.group(1)] = m.group(2)
    rows = {}
    for key, (result, result_type) in flags.items():
        number = numbers[key]
        # an alias spells an opcode a second time; the first name the header gives it is the one kept
        if number not in rows:
            rows[number] = (number, names.get(key, "Op" + key), result, result_type)
    return [rows[n] for n in sorted(rows)], f"{version} revision {revision}"


def emit(rows: list[tuple[int, str, bool, bool]], version: str) -> str:
    lines = [
        "// Generated by libs/data/babel-data/tools/gen-spirv-opcodes.py from extern/spirv-reflect's spirv.h; do not edit.",
        f"// SPIR-V {version}.",
        "",
        '#include "spirv.hh"',
        "",
        "namespace babel::spirv::impl",
        "{",
        "extern opcode_info const k_opcode_table[] = {",
    ]
    for number, name, result, result_type in rows:
        lines.append(f'    {{{number}, {"true" if result else "false"}, {"true" if result_type else "false"}, "{name}"}},')
    lines += ["};", f"extern isize const k_opcode_count = {len(rows)};", "} // namespace babel::spirv::impl", ""]
    return "\n".join(lines)


def find_clang_format(explicit: str | None) -> str:
    if explicit:
        return explicit
    pinned = REPO / "tools" / "bin" / ("clang-format.exe" if os.name == "nt" else "clang-format")
    if pinned.exists():
        return str(pinned)
    found = shutil.which("clang-format")
    if found:
        return found
    sys.exit("gen-spirv-opcodes: no clang-format found; pass --clang-format PATH")


def clang_format(text: str, exe: str) -> str:
    result = subprocess.run(
        [exe, f"--assume-filename={TABLE}", f"--style=file:{REPO / '.clang-format'}"],
        input=text.encode("utf-8"),
        capture_output=True,
        check=True,
    )
    return result.stdout.decode("utf-8").replace("\r\n", "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated table")
    mode.add_argument("--check", action="store_true", help="exit 2 when the committed table differs from the output")
    parser.add_argument("--clang-format", help="the clang-format to format the output with")
    args = parser.parse_args()

    rows, version = read_header()
    text = clang_format(emit(rows, version), find_clang_format(args.clang_format))
    differs = not TABLE.exists() or TABLE.read_bytes().decode("utf-8").replace("\r\n", "\n") != text
    if args.write:
        if differs:
            TABLE.parent.mkdir(parents=True, exist_ok=True)
            TABLE.write_bytes(text.encode("utf-8"))
        print(f"gen-spirv-opcodes: {'wrote' if differs else 'left'} {TABLE.relative_to(REPO).as_posix()}, {len(rows)} opcodes")
        return 0
    if differs:
        print(f"gen-spirv-opcodes: {TABLE.relative_to(REPO).as_posix()} differs from the generator's output")
        print(f"gen-spirv-opcodes: run `{COMMAND}`")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
