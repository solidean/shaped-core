/// What the tests append to the tessellation file, which is how they reach its `@internal` functions.
constexpr cc::string_view k_harness = R"(

struct tessellation_hash:
    h: uint
    points: int
    indices: int
    is_in_order: bool

fun tessellation_point(s: mut tessellation_hash, at: int, u: uint, v: uint):
    s.is_in_order = s.is_in_order and at == s.points
    s.points += 1
    s.h = (s.h ^ u) * 16777619u
    s.h = (s.h ^ v) * 16777619u

fun tessellation_index(s: mut tessellation_hash, at: int, index: int):
    s.is_in_order = s.is_in_order and at == s.indices
    s.indices += 1
    s.h = (s.h ^ (index as uint)) * 16777619u

fun tessellation_hash_of(p: tessellation_patch, output: int){sg_tessellation_points, sg_tessellation_indices} -> uint:
    let counted = (2166136261u ^ (p.point_count as uint)) * 16777619u
    let mut s = tessellation_hash((counted ^ (p.index_count as uint)) * 16777619u, 0, 0, true)
    tessellate(p, output, mut s)
    if s.points != p.point_count or s.indices != p.index_count or not s.is_in_order => return 0u
    return s.h
)";

cc::string float_text(float x)
{
    auto text = cc::format("{}", x);
    return text.contains('.') || text.contains('e') ? text : text + ".0";
}

/// The tessellation file with the harness and one test per case behind it, run as that prelude file.
cc::string failures_of(cc::span<tessellation_case const> cases)
{
    auto source = cc::string(sgl::impl::embedded_tessellation_prelude());
    source += k_harness;
    for (auto const& c : cases)
    {
        auto const call
            = cc::format("tessellation_patch_of({}, {}, float4({}, {}, {}, {}), float2({}, {}))", c.domain,
                         c.partitioning, float_text(c.edges[0]), float_text(c.edges[1]), float_text(c.edges[2]),
                         float_text(c.edges[3]), float_text(c.inside[0]), float_text(c.inside[1]));
        source.appendf("\ntest {{sg_tessellation_points, sg_tessellation_indices}}:\n    let p = {}\n    p.point_count "
                       "== {}\n    p.index_count == {}\n"
                       "    tessellation_hash_of(p, {}) == {}u\n",
                       call, c.points, c.indices, c.output, c.hash);
    }

    // the library's other prelude files shared, this one as the source's, and an empty program behind them
    auto const shared = sgl::parsed_prelude();
    auto const own = sgl::i32(shared.size()) - 1;
    cc::string_view const sources[] = {source, ""};
    auto checked = sgl_test::check_behind(shared.subspan(cc::start_end{.start = 0, .end = own}), sources);
    REQUIRE(sgl_test::reports_of(checked) == "");
    auto files = cc::vector<sgl::check::module_file>();
    for (auto i = isize(0); i < checked.files.size(); ++i)
        files.push_back({.file = *checked.files[i], .ast = *checked.asts[i]});
    auto const results = sgl::test::run_tests(checked.module, files, {.file = own, .limits = {.fuel = 2'000'000'000}});
    CHECK(results.size() == cases.size());
    auto shown = cc::vector<sgl::check::located_diagnostic>();
    for (auto const& r : results)
        if (!r.is_passed())
            shown.push_back(sgl::test::diagnostic_of(checked.module, r));
    checked.module.diagnostics = cc::move(shown);
    return sgl_test::reports_of(checked);
}
