/// The overloads an operation takes; none for one whose name has no overload.
enum dx_overload_mask : u8
{
    k_no_overload = 0,
    k_f16 = 1 << 0,
    k_f32 = 1 << 1,
    k_f64 = 1 << 2,
    k_i1 = 1 << 3,
    k_i16 = 1 << 4,
    k_i32 = 1 << 5,
    k_i64 = 1 << 6,
    k_floats = k_f16 | k_f32 | k_f64,
    k_ints = k_i16 | k_i32 | k_i64,
    k_scalars = k_floats | k_ints,
};

