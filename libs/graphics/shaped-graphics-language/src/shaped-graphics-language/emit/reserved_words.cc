cc::span<cc::string_view const> sgl::emit::reserved_words(target t)
{
    switch (t)
    {
    case target::hlsl_dx12:
    case target::hlsl_vulkan:
        return k_hlsl;
    case target::wgsl:
        return k_wgsl;
    case target::msl:
        return k_msl;
    }
    return {};
}

bool sgl::emit::is_reserved(target t, cc::string_view name)
{
    for (auto const word : reserved_words(t))
        if (word == name)
            return true;
    return false;
}
