#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///

"""Embed a recorded shader bundle into an executable, as sc_embed_shader_bundle's build step.

    uv run embed_shader_bundle.py --bundle <file> --out <file.cc>

The .cc holds the bundle's bytes and registers them with slib before main.
An empty bundle is valid and registers nothing, so a frozen build that was never recorded still builds and compiles every shader at run time.
Written only when its text changes, so an unchanged recording rebuilds nothing.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def render(data: bytes) -> str:
    lines = [
        "// Generated by embed_shader_bundle.py from a recorded shader bundle; do not edit.",
        "#include <clean-core/container/span.hh>",
        "#include <shaped-shader-library/shader_bundle.hh>",
        "",
        "namespace",
        "{",
        # A zero-length array is ill-formed, so an empty bundle still holds one byte, which its size leaves out.
        "alignas(16) constexpr unsigned char k_bundle[] = {",
    ]
    body = data if data else b"\0"
    for start in range(0, len(body), 32):
        lines.append("    " + ",".join(str(b) for b in body[start:start + 32]) + ",")
    lines += [
        "};",
        "",
        "struct bundle_registration",
        "{",
        "    bundle_registration()",
        "    {",
        f"        slib::register_shader_bundle(cc::span<cc::byte const>(reinterpret_cast<cc::byte const*>(k_bundle), {len(data)}));",
        "    }",
        "};",
        "",
        "bundle_registration const g_bundle_registration;",
        "} // namespace",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--bundle", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    text = render(args.bundle.read_bytes() if args.bundle.is_file() else b"")
    if not args.out.is_file() or args.out.read_text(encoding="utf-8") != text:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
